    const b = bounds(key, c.h), inset = 0.04;
    const L = clamp(c.L, lerp(b.Lmin, b.Lmax, inset), lerp(b.Lmax, b.Lmin, inset));
    const C = clamp(c.C, lerp(b.Cmin, b.Cmax, inset), lerp(b.Cmax, b.Cmin, inset));
